    window.translations = translations;

    window.changeLang = function (lang) {
        if (!translations[lang]) return;
        const t = translations[lang];
        localStorage.setItem('pixkit_lang', lang);

        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            if (t[key]) {
                if (el.tagName === 'INPUT' && el.getAttribute('placeholder')) {
                    el.setAttribute('placeholder', t[key]);
                } else {
                    el.innerHTML = t[key];
                }
            }
        });

        const langNameEl = document.getElementById('currentLangName');
        if (langNameEl) langNameEl.textContent = t.langName;

        // Update document lang
        document.documentElement.lang = lang;

        if (window.renderQueue) window.renderQueue();
    };

    // Auto-initialize on load
    document.addEventListener('DOMContentLoaded', () => {
        const savedLang = localStorage.getItem('pixkit_lang') || 'ko';
        window.changeLang(savedLang);
    });
