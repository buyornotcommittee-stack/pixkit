    window.translations = translations;

    window.changeLang = function (lang) {
        if (!translations[lang]) return;
        const t = translations[lang];
        const langNameEl = document.getElementById('currentLangName');
        if (langNameEl) langNameEl.textContent = t.langName;

        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            if (t[key]) {
                if (el.tagName === 'INPUT' && el.hasAttribute('placeholder')) {
                    el.placeholder = t[key];
                } else {
                    el.innerHTML = t[key];
                }
            }
        });

        const presetSelect = document.getElementById('presetSelect');
        if (presetSelect && presetSelect.options[0]) {
            presetSelect.options[0].textContent = t.custom_size;
        }

        if (window.renderQueue) window.renderQueue();
    };

    // Auto-initialize on load
    document.addEventListener('DOMContentLoaded', () => {
        const savedLang = localStorage.getItem('pixkit_lang') || 'ko';
        window.changeLang(savedLang);
    });
